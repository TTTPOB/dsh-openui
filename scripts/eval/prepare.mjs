#!/usr/bin/env node
/**
 * Prepare an isolated DSH_HOME for real-model evaluation.
 * Copies only provider/auth configuration from the user home; never copies
 * sessions, storages, attachments, logs, plugins, or AGENTS.md.
 */
import {
  chmodSync, copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync,
} from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, resolve, sep } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'

const ROOT = resolve(fileURLToPath(new URL('../../', import.meta.url)))
const PLUGIN_DIR = join(ROOT, 'packages/dsh-openui')
const PROVIDER_ROWS = ['llm-deepseek', 'llm-pi-ai', 'llm-deepseek-account']
const AUTH_FILES = ['.credentials.yaml', '.env']

function fail(message) {
  console.error('prepare: ' + message)
  process.exit(1)
}

function assertInsideRoot(path) {
  const resolved = resolve(path)
  if (resolved === ROOT || !resolved.startsWith(ROOT + sep)) {
    fail('eval home must be inside the workspace: ' + resolved)
  }
  return resolved
}

function extractRows(text, names) {
  const wanted = new Set(names)
  const rows = []
  let current = null
  for (const line of text.split(/\r?\n/)) {
    if (line.startsWith('- ')) {
      if (current !== null) { rows.push(current.join('\n')); current = null }
      const match = /^- id:\s*([^\s]+)/.exec(line)
      if (match !== null && wanted.has(match[1])) current = [line]
    } else if (current !== null) {
      current.push(line)
    }
  }
  if (current !== null) rows.push(current.join('\n'))
  return rows
}

function rowIds(rows) {
  return rows.map(row => {
    const match = /^- id:\s*([^\s]+)/.exec(row)
    return match === null ? '?' : match[1]
  })
}

function writeMode(path, content, mode) {
  mkdirSync(dirname(path), { recursive: true, mode: 0o700 })
  writeFileSync(path, content, { mode })
  chmodSync(path, mode)
}

function copyAuthFile(sourceHome, destHome, name, check) {
  const source = join(sourceHome, name)
  if (!existsSync(source)) return { name, copied: false }
  const bytes = statSync(source).size
  if (!check) {
    const dest = join(destHome, name)
    copyFileSync(source, dest)
    chmodSync(dest, 0o600)
  }
  return { name, copied: true, bytes }
}

function modelPatch(provider, model) {
  return [
    '- id: agent-default-model',
    '  config:',
    '    provider: ' + JSON.stringify(provider),
    '    model: ' + JSON.stringify(model),
    '- id: session-title-llm',
    '  disabled: true',
    '- id: directory-picker',
    '  disabled: true',
    '- insert:',
    '    - id: directory-picker-browse',
    "      name: '@deepseek-ai/dsh-host-directory-picker-browse'",
    '    - id: ui-directory-picker-browse',
    "      name: '@deepseek-ai/dsh-client-ui-directory-picker-browse'",
    '',
  ].join('\n')
}

export function providerPatchPath(home) {
  return join(home, 'provider.patch.yml')
}

export function modelPatchPath(home) {
  return join(home, 'model.patch.yml')
}

export function prepareHome({ home, sourceHome, provider, model, check = false }) {
  const destHome = assertInsideRoot(home)
  const srcHome = resolve(sourceHome)
  const profilePatch = join(srcHome, 'profiles/web/cordis.patch.yml')
  if (!existsSync(profilePatch)) fail('provider config not found: ' + profilePatch)
  const rows = extractRows(readFileSync(profilePatch, 'utf8'), PROVIDER_ROWS)
  if (rows.length === 0) fail('no provider rows (' + PROVIDER_ROWS.join(', ') + ') found in ' + profilePatch)
  if (!check) mkdirSync(destHome, { recursive: true, mode: 0o700 })
  const auth = AUTH_FILES.map(name => copyAuthFile(srcHome, destHome, name, check))
  const summary = {
    sourceHome: srcHome,
    destHome,
    profilePatch,
    providerRows: rowIds(rows),
    auth,
    check,
  }
  if (check) return summary

  mkdirSync(destHome, { recursive: true, mode: 0o700 })
  mkdirSync(join(destHome, 'workspace'), { recursive: true, mode: 0o700 })
  writeMode(providerPatchPath(destHome), [
    '# Generated by scripts/eval/prepare.mjs.',
    '# Contains only provider rows copied from the user profile patch.',
    ...rows,
    '',
  ].join('\n'), 0o600)
  if (provider !== undefined && model !== undefined) {
    writeMode(modelPatchPath(destHome), modelPatch(provider, model), 0o600)
  }

  const env = { ...process.env, DSH_HOME: destHome }
  const workspace = join(destHome, 'workspace')
  const init = spawnSync('dsh', ['--profile', 'web', '--dump-config'], {
    cwd: workspace, env, encoding: 'utf8', timeout: 120000,
  })
  if (init.error) throw init.error
  if (init.status !== 0) fail('dsh --dump-config failed: ' + String(init.stderr ?? '').slice(-2000))

  const built = ['dist/index.js', 'dist/client.js', 'dist/island.js', 'dist/openui-skill.md']
  for (const file of built) {
    if (!existsSync(join(PLUGIN_DIR, file))) fail('build dsh-openui first; missing ' + file)
  }
  const install = spawnSync('dsh', [
    'plugin', '--profile', 'web', 'add', 'link:' + PLUGIN_DIR,
    '--config.auto-install-peers=false',
  ], { cwd: workspace, env, encoding: 'utf8', timeout: 120000 })
  if (install.error) throw install.error
  if (install.status !== 0) fail('dsh plugin add failed: ' + String(install.stderr ?? '').slice(-2000))
  return summary
}

const isMain = process.argv[1] === fileURLToPath(import.meta.url)
if (isMain) {
  const { values } = parseArgs({ options: {
    home: { type: 'string', default: process.env.DSH_EVAL_HOME ?? '.demo-home/eval/current' },
    'source-home': { type: 'string', default: process.env.DSH_EVAL_SOURCE_HOME ?? join(homedir(), '.dsh') },
    provider: { type: 'string' },
    model: { type: 'string' },
    check: { type: 'boolean', default: false },
  } })
  const home = resolve(ROOT, values.home)
  const summary = prepareHome({
    home, sourceHome: values['source-home'], provider: values.provider, model: values.model, check: values.check,
  })
  console.log(JSON.stringify(summary, null, 2))
}
