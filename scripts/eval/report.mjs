#!/usr/bin/env node
/** Aggregate eval JSONL into a Markdown evidence report. */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'

const ROOT = resolve(fileURLToPath(new URL('../..', import.meta.url)))
const { values } = parseArgs({ options: {
  input: { type: 'string' },
  out: { type: 'string' },
} })
if (values.input === undefined) {
  console.error('usage: node scripts/eval/report.mjs --input docs/evidence/eval-YYYY-MM-DD.jsonl [--out ...md]')
  process.exit(2)
}
const input = resolve(ROOT, values.input)
if (!existsSync(input)) throw new Error('missing ' + input)
const records = readFileSync(input, 'utf8').split('\n').filter(Boolean).map(line => JSON.parse(line))
const out = resolve(ROOT, values.out ?? input.replace(/\.jsonl$/, '.md'))
const pct = (part, total) => total === 0 ? '—' : (100 * part / total).toFixed(1) + '%'
const keyOf = record => record.run.provider + '/' + record.run.model
const groups = ['should-ui', 'should-not-ui']

function summarize(rows) {
  const total = rows.length
  const count = predicate => rows.filter(predicate).length
  return {
    total,
    pass: count(row => row.scoring.verdict === 'pass'),
    partial: count(row => row.scoring.verdict === 'partial'),
    fail: count(row => row.scoring.verdict === 'fail'),
    error: count(row => row.scoring.verdict === 'error'),
    triggered: count(row => row.scoring.triggered === true),
    rendered: count(row => row.scoring.rendered === true),
    skill: count(row => row.response?.skillLoaded === true),
    check: count(row => row.scoring.openuiCheckCalled === true),
    local: count(row => row.scoring.localRecompute === true),
  }
}

const lines = []
lines.push('# Real-model OpenUI eval')
lines.push('')
lines.push('Generated by scripts/eval/report.mjs from ' + values.input + '.')
lines.push('Credentials are never included; the isolated eval home lives under .demo-home/eval/ and is not committed.')
const build = records.find(record => record.build !== undefined)?.build
if (build !== undefined) {
  lines.push('Build: commit ' + (build.commit ?? 'unknown') + ' (dirty=' + String(build.dirty) + '), snapshot ' + build.snapshot + ', island sha256 ' + (build.sha256?.['dist/island.js'] ?? '?'))
}
lines.push('')
lines.push('## Commands')
lines.push('')
lines.push('```sh')
lines.push('flock .locks/demo.lock node scripts/eval/run-all.mjs')
lines.push('node scripts/eval/report.mjs --input ' + values.input)
lines.push('```')
lines.push('')
lines.push('## Summary')
lines.push('')
lines.push('| model | group | n | pass | partial | fail | error | triggered | rendered | skill loaded | openui_check | local recompute |')
lines.push('|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|')
for (const model of [...new Set(records.map(keyOf))].sort()) {
  for (const group of groups) {
    const rows = records.filter(record => keyOf(record) === model && record.case.group === group)
    if (rows.length === 0) continue
    const s = summarize(rows)
    lines.push('| ' + model + ' | ' + group + ' | ' + s.total + ' | ' + s.pass + ' | ' + s.partial + ' | ' + s.fail + ' | ' + s.error
      + ' | ' + s.triggered + ' (' + pct(s.triggered, s.total) + ')'
      + ' | ' + s.rendered + ' (' + pct(s.rendered, s.total) + ')'
      + ' | ' + s.skill + ' (' + pct(s.skill, s.total) + ')'
      + ' | ' + s.check + ' (' + pct(s.check, s.total) + ')'
      + ' | ' + s.local + ' (' + pct(s.local, s.total) + ') |')
  }
}
lines.push('')
lines.push('## Per-case')
lines.push('')
lines.push('| model | case | group | skill | check | triggered | rendered | local | verdict |')
lines.push('|---|---|---|---|---|---|---|---|---|')
for (const record of records) {
  lines.push('| ' + keyOf(record) + ' | ' + record.case.id + ' | ' + record.case.group
    + ' | ' + (record.response?.skillLoaded === true ? 'yes' : 'no')
    + ' | ' + (record.scoring.openuiCheckCalled === true ? 'yes' : 'no')
    + ' | ' + (record.scoring.triggered === true ? 'yes' : 'no')
    + ' | ' + (record.scoring.rendered === true ? 'yes' : 'no')
    + ' | ' + (record.scoring.localRecompute === true ? 'yes' : 'no')
    + ' | ' + record.scoring.verdict + ' |')
}
lines.push('')
lines.push('## Failure samples')
lines.push('')
const failures = records.filter(record => record.scoring.verdict !== 'pass')
if (failures.length === 0) lines.push('None.')
else {
  for (const record of failures.slice(0, 20)) {
    lines.push('### ' + keyOf(record) + ' · ' + record.case.id + ' · ' + record.scoring.verdict)
    lines.push('')
    lines.push('- prompt: ' + record.case.prompt)
    if (record.error !== undefined) lines.push('- error: ' + record.error)
    lines.push('- triggered=' + record.scoring.triggered + '; rendered=' + record.scoring.rendered
      + '; skillLoaded=' + (record.response?.skillLoaded === true) + '; openuiCheck=' + (record.scoring.openuiCheckCalled === true) + '; localRecompute=' + record.scoring.localRecompute)
    if (record.response?.rawMarkdown !== undefined) {
      lines.push('')
      lines.push('```text')
      lines.push(record.response.rawMarkdown.slice(0, 2500))
      lines.push('```')
    }
    lines.push('')
  }
}
writeFileSync(out, lines.join('\n') + '\n')
console.log('wrote ' + out + ' (' + records.length + ' records)')
