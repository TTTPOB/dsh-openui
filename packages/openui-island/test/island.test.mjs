import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
const dom = new JSDOM('<!doctype html><div id="host"></div>', { pretendToBeVisual: true, url: 'http://localhost/' });
for (const key of ['window', 'document', 'HTMLElement', 'HTMLInputElement', 'Event', 'MutationObserver']) globalThis[key] = dom.window[key];
Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
const { mount } = await import(new URL('../' + (process.env.OPENUI_OUT_DIR ?? 'dist') + '/island.js', import.meta.url));
const loan = await readFile(new URL('../examples/loan.openui', import.meta.url), 'utf8');
const settle = async () => { await new Promise(resolve => setTimeout(resolve, 50)); await new Promise(resolve => setImmediate(resolve)); };
test('React 19 island computes the loan locally and cleans up its shadow DOM', async () => {
  const root = document.getElementById('host').attachShadow({ mode: 'open' });
  const actions = [], errors = [];
  let ready = 0;
  const headBefore = document.head.innerHTML;
  const handle = mount(root, { response: loan, onAction: action => actions.push(action), onError: error => errors.push(error), onReady: () => ready++ });
  await settle();
  assert.equal(root.querySelectorAll('input[type="range"]').length, 3);
  assert.match(root.textContent, /76.19%/);
  assert.match(root.textContent, /1.80/);
  assert.match(root.textContent, /DECLINE/);
  assert.match(globalThis.__DSH_OPENUI_ISLAND__.reactVersion, /^19\./);
  assert.ok(ready > 0);
  assert.deepEqual(errors, []);
  const slider = root.querySelector('input');
  Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(slider, '0');
  slider.dispatchEvent(new Event('input', { bubbles: true, composed: true }));
  slider.dispatchEvent(new Event('change', { bubbles: true, composed: true }));
  await settle();
  assert.match(root.textContent, /52.38%/);
  assert.match(root.textContent, /REVIEW/);
  assert.deepEqual(actions, []);
  handle.update({ theme: 'dark' });
  await settle();
  assert.match(root.textContent, /52.38%/);
  assert.equal(root.querySelector('[data-theme]').dataset.theme, 'dark');
  assert.equal(document.head.innerHTML, headBefore);
  handle.unmount(); handle.unmount();
  assert.equal(root.childNodes.length, 0);
});
test('streaming updates and local Button never emit side-effect actions', async () => {
  const host = document.createElement('div'); document.body.append(host);
  const root = host.attachShadow({ mode: 'open' });
  const actions = [], errors = [];
  const handle = mount(root, { response: 'root = Card("Loading", [', streaming: true, onAction: event => actions.push(event), onError: error => errors.push(error) });
  await settle();
  assert.deepEqual(errors, []);
  handle.update({ response: '$amount = 5\nroot = Card("Local", [Button("Reset", $amount, 0), Text($amount)])', streaming: false });
  await settle();
  assert.equal(root.querySelector('output').textContent, '5');
  root.querySelector('button').click();
  await settle();
  assert.equal(root.querySelector('output').textContent, '0');
  assert.deepEqual(actions, []);
  assert.deepEqual(errors, []);
  handle.unmount(); host.remove();
});
test('saved reactive state restores on remount; fresh mount uses defaults', async () => {
  const host = document.createElement('div'); document.body.append(host);
  const root = host.attachShadow({ mode: 'open' });
  let saved;
  let handle = mount(root, { response: loan, initialState: { $monthly: 0 }, onStateChange: state => { saved = state; } });
  await settle();
  assert.match(root.textContent, /52.38%/);
  const slider = root.querySelector('input');
  Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(slider, '1');
  slider.dispatchEvent(new Event('input', { bubbles: true, composed: true }));
  await settle();
  assert.equal(saved.$monthly, 1);
  handle.unmount();
  handle = mount(root, { response: loan, initialState: saved });
  await settle();
  assert.match(root.textContent, /57.14%/);
  handle.unmount();
  handle = mount(root, { response: loan });
  await settle();
  assert.match(root.textContent, /76.19%/);
  handle.unmount(); host.remove();
});
test('generic layout, tone, table and SVG series react without domain-specific rules', async () => {
  const host = document.createElement('div'); document.body.append(host);
  const root = host.attachShadow({ mode: 'open' });
  const errors = [];
  const handle = mount(root, { response: '$n = 2\nroot = Card("General", [Row([Button("Zero", $n, 0)]), Grid([Metric("State", "DECLINE", "text", "positive"), Metric("Number", $n, "decimal", $n > 0 ? "warning" : "neutral")], 2), Table("Data", ["Name", "Value"], [["A", $n]]), Chart("Line", "line", ["A", "B", "C"], [-5, $n, 0]), Chart("Zero", "bar", ["A"], [0])])', onError: error => errors.push(error) });
  await settle();
  assert.equal(root.querySelector('[data-tone="positive"] output').textContent, 'DECLINE');
  assert.equal(root.querySelector('tbody td:last-child').textContent, '2');
  assert.equal(root.querySelectorAll('svg').length, 2);
  assert.equal(root.querySelectorAll('circle').length, 3);
  assert.ok(!/NaN|Infinity/.test(root.querySelector('svg').outerHTML));
  const before = root.querySelector('polyline').getAttribute('points');
  root.querySelector('button').click();
  await settle();
  assert.equal(root.querySelector('tbody td:last-child').textContent, '0');
  assert.notEqual(root.querySelector('polyline').getAttribute('points'), before);
  assert.equal(root.querySelector('[data-tone="neutral"] output').textContent, '0.00');
  assert.deepEqual(errors, []);
  handle.unmount(); host.remove();
});
test('custom functions evaluate reactively and domain failures reach onError', async () => {
  const host = document.createElement('div'); document.body.append(host);
  const root = host.attachShadow({ mode: 'open' });
  const errors = [];
  const response = await readFile(new URL('../examples/functions.openui', import.meta.url), 'utf8');
  const handle = mount(root, { response, onError: error => errors.push(error) });
  await settle();
  assert.match(root.textContent, /5.00/);
  assert.match(root.textContent, /1,234,567.89/);
  const slider = root.querySelector('input');
  Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(slider, '36');
  slider.dispatchEvent(new Event('input', { bubbles: true, composed: true }));
  await settle();
  assert.match(root.textContent, /6.00/);
  assert.deepEqual(errors, []);
  handle.update({ response: 'root = Card("Bad", [Text(@sqrt(-1))])' });
  await settle();
  assert.match(JSON.stringify(errors), /@sqrt/);
  handle.unmount(); host.remove();
});
