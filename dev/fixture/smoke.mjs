import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { OpenUIFixtureAdapter, Config, apply } from './dist/index.js'
const home = new URL('../../test-results/fixture-smoke/', import.meta.url)
mkdirSync(home, { recursive: true })
const replyFile = fileURLToPath(new URL('reply.md', home))
const callsFile = fileURLToPath(new URL('calls.jsonl', home))
writeFileSync(replyFile, '本地回复 '.repeat(30))
writeFileSync(callsFile, '')
const config = Config({ replyFile, callsFile, paceMs: 0 })
assert.equal(Config({ replyFile, callsFile }).paceMs, 20)
assert.throws(() => apply({}, { ...config, replyFile: 'relative.md' }))
const adapter = new OpenUIFixtureAdapter(config)
assert.equal((await adapter.listModels('openui-fixture'))[0].id, 'openui-fixture')
const collect = async options => { const chunks = []; for await (const c of adapter.stream(options)) chunks.push(c); return chunks }
const chunks = await collect({ provider: 'openui-fixture', model: 'openui-fixture', messages: [], sessionId: 'smoke' })
assert.equal(chunks.filter(c => c.type === 'text-delta').map(c => c.text).join(''), readFileSync(replyFile, 'utf8'))
assert.equal(chunks.at(-1).reason.kind, 'stop')
assert.ok(chunks.every(c => c.blockType !== 'tool-call'))
writeFileSync(replyFile, 'changed reply')
const next = await collect({ messages: [] })
assert.equal(next.find(c => c.type === 'text-delta').text, 'changed reply')
const signal = AbortSignal.abort()
await assert.rejects(collect({ messages: [], signal }))
assert.equal(readFileSync(callsFile, 'utf8').trim().split('\n').length, 2)
console.log('PASS fixture: chunked text, per-call file read, call count=2, abort, no tools')
const probe = new OpenUIFixtureAdapter({ ...config, checkSources: ['root = Card("ok", [])', 'root = Missing()'] })
const user = { role: 'user', content: [{ type: 'text', text: 'check' }] }
const capture = async messages => { const result = []; for await (const chunk of probe.stream({ messages })) result.push(chunk); return result }
const toolChunks = await capture([user])
const calls = toolChunks.filter(chunk => chunk.type === 'block-end').map(chunk => chunk.block)
assert.equal(calls.length, 2)
assert.equal(calls[0].name, 'openui_check')
assert.equal(JSON.parse(calls[1].arguments).source, 'root = Missing()')
assert.equal(toolChunks.at(-1).reason.kind, 'tool-calls')
const history = [user, { role: 'assistant', content: calls }, ...calls.map(call => ({ role: 'tool', source: { kind: 'tool', callId: call.id }, content: [{ type: 'text', text: '{"ok":true}' }] }))]
const reply = await capture(history)
assert.equal(reply.at(-1).reason.kind, 'stop')
assert.equal(reply.find(chunk => chunk.type === 'text-delta').text, 'changed reply')
assert.equal((await capture([...history, user])).at(-1).reason.kind, 'tool-calls')
const logs = readFileSync(callsFile, 'utf8').trim().split('\n').map(line => JSON.parse(line))
assert.equal(logs[0].toolMessages, undefined)
assert.deepEqual(logs[2].toolMessages, [])
assert.equal(logs[3].toolMessages.length, 2)
assert.equal(logs[3].toolMessages[0].content[0].text, '{"ok":true}')
assert.deepEqual(logs[4].toolMessages, [])
console.log('PASS optional checkSources: two calls, logged results resume text, new user checks again')
const ptc = new OpenUIFixtureAdapter({ ...config, checkSources: ['root = Card("ok", [])'], checkMode: 'ptc' })
const ptcChunks = []
for await (const chunk of ptc.stream({ messages: [{ role: 'system', content: [{ type: 'text', text: 'SDK includes openui_check' }] }, user], tools: [{ name: 'run_code' }] })) ptcChunks.push(chunk)
const ptcCall = ptcChunks.find(chunk => chunk.type === 'block-end').block
assert.equal(ptcCall.name, 'run_code')
assert.equal(JSON.parse(ptcCall.arguments).code, 'return await tools.openui_check(' + JSON.stringify({ source: 'root = Card("ok", [])' }) + ');')
const ptcLog = JSON.parse(readFileSync(callsFile, 'utf8').trim().split('\n').at(-1))
assert.deepEqual(ptcLog.toolNames, ['run_code'])
assert.equal(ptcLog.sdkMentionsOpenUICheck, true)
assert.deepEqual(ptcLog.toolMessages, [])
console.log('PASS PTC fixture: run_code invokes SDK check, only tool names and SDK-presence boolean logged')
